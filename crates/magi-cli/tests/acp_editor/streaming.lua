return function(ctx)
  local session, completed = ctx.session, ctx.completed
  local chat, submit, wait_for, screen = ctx.chat, ctx.submit, ctx.wait_for, ctx.screen
  submit("editor-stream-first")
  wait_for("visible streaming prefix", function() return chat():find("part-0", 1, true) ~= nil end)
  assert(session.is_generating, "stream must appear before final response")
  assert(#completed == 0, "no early completion")
  vim.fn.writefile(vim.split(chat(), "\n", { plain = true }), "../streaming.txt")
  screen("streaming-screen.txt", "part-0")
  vim.fn.writefile({ "prefix-visible" }, "../stream-ready")
  wait_for("first native completion", function() return #completed == 1 end)
  assert(completed[1].success, vim.inspect(completed[1].error))
  assert(not session.is_generating)
  submit("editor-stream-second")
  wait_for("second visible prefix", function() return chat():find("part-1", 1, true) ~= nil end)
  assert(session.is_generating)
  vim.fn.writefile({ "second-visible" }, "../second-ready")
  wait_for("second native completion", function() return #completed == 2 end)
  assert(completed[2].success, vim.inspect(completed[2].error))
  screen("completed-screen.txt", "part-1-done")
  submit("editor-cancel-third")
  wait_for("cancellable streaming prefix", function() return chat():find("part-2", 1, true) ~= nil end)
  assert(session.is_generating and #completed == 2)
  vim.fn.writefile({ "cancel-prefix-visible" }, "../cancel-ready")
  wait_for("native cancellation handshake", function() return vim.fn.filereadable("../cancel-go") == 1 end)
  ctx.agentic.stop_generation()
  wait_for("native cancelled response", function() return #completed == 3 end)
  assert(completed[3].success, vim.inspect(completed[3].error))
  assert(chat():find("Generation stopped by the user request", 1, true))
  assert(not chat():find("part-2-done", 1, true), "cancelled provider must not finish")
  assert(not session.is_generating)
  screen("cancelled-screen.txt", "Generation stopped")
  submit("editor-recover-fourth")
  wait_for("post-cancel streaming", function() return chat():find("part-3", 1, true) ~= nil end)
  assert(session.is_generating)
  vim.fn.writefile({ "recovery-prefix-visible" }, "../recovery-ready")
  wait_for("post-cancel completion", function() return #completed == 4 end)
  assert(completed[4].success, vim.inspect(completed[4].error))
  assert(not chat():find("part-2-done", 1, true))
  screen("recovery-screen.txt", "part-3-done")
  assert(chat():find("editor-stream-first", 1, true))
  assert(chat():find("editor-stream-second", 1, true))
  return { cancelled_turns = 1, post_cancel_recovery = true }
end
